<?php

declare(strict_types=1);

namespace App\Controllers\MasterData;

use App\Core\Config;
use App\Core\Request;
use App\Core\Response;
use App\Core\Router;
use App\Core\View;
use App\Repositories\AuditRepository;
use App\Repositories\SubjectRepository;
use App\Services\AuthorizationService;
use App\Services\MasterDataService;

/**
 * Subjects (MD-03).
 *
 * A subject belongs to a department, so every write passes through
 * `guardDepartment()`: a dean cannot create a subject for another department by
 * editing the posted `department_id`. Reads are scoped by the repository, and
 * `edit` loads through `findInScope()` so an out-of-scope id is a 404.
 *
 * `units`, `lecture_hours` and `lab_hours` are validated as decimals with a
 * sane ceiling; `contact_hours` is generated by the database and never posted.
 */
final class SubjectController extends MasterDataController
{
    public function __construct(
        Request $request,
        View $view,
        Router $router,
        Config $config,
        MasterDataService $masterData,
        AuthorizationService $authorization,
        AuditRepository $audit,
        private readonly SubjectRepository $subjects
    ) {
        parent::__construct($request, $view, $router, $config, $masterData, $authorization, $audit);
    }

    public function index(Request $request): Response
    {
        $scope = $this->scope($request);
        $filters = [
            'search' => (string) $request->query('q', ''),
            'status' => (string) $request->query('status', ''),
            'department_id' => $request->query('department'),
            'subject_type' => (string) $request->query('type', ''),
            'sort' => (string) $request->query('sort', ''),
            'direction' => (string) $request->query('direction', ''),
        ];
        $pagination = $this->pagination($request);
        $result = $this->subjects->paginate($scope, $filters, $pagination['per_page'], $pagination['offset']);
        $user = $this->actor($request);

        return $this->view('master/subjects/index', [
            'title' => 'Subjects',
            'subjects' => $result['rows'],
            'total' => $result['total'],
            'filters' => $filters,
            'departments' => $this->departmentOptions($scope),
            'subject_types' => SubjectRepository::TYPES,
            'page' => $pagination['page'],
            'per_page' => $pagination['per_page'],
            'last_page' => $this->lastPage($result['total'], $pagination['per_page']),
            'notice' => $this->notice($request),
            'can_create' => $this->authorization->can($user, 'subjects.create'),
            'can_edit' => $this->authorization->can($user, 'subjects.update'),
            'can_archive' => $this->authorization->can($user, 'subjects.delete'),
        ]);
    }

    public function create(Request $request): Response
    {
        return $this->form($request, null);
    }

    public function store(Request $request): Response
    {
        $scope = $this->scope($request);
        $data = $this->validateSubject($request);
        $data['department_id'] = $this->guardDepartment($scope, (int) $data['department_id']);
        $this->guardUnique($this->subjects->codeExists($data['code']), 'code', 'That subject code is already in use.');

        $id = $this->subjects->create($data);
        $this->auditChange($request, 'master.subject.created', 'subject', $id, 'Created subject ' . $data['code']);

        return $this->saved('master.subjects.index', 'created');
    }

    public function edit(Request $request, string $id): Response
    {
        return $this->form($request, $this->load($request, (int) $id));
    }

    public function update(Request $request, string $id): Response
    {
        $record = $this->load($request, (int) $id);
        $scope = $this->scope($request);
        $data = $this->validateSubject($request);
        $data['department_id'] = $this->guardDepartment($scope, (int) $data['department_id']);
        $this->guardUnique(
            $this->subjects->codeExists($data['code'], (int) $record['id']),
            'code',
            'That subject code is already in use.'
        );

        $this->subjects->update((int) $record['id'], $data);
        $this->auditChange($request, 'master.subject.updated', 'subject', (int) $record['id'], 'Updated subject ' . $data['code']);

        return $this->saved('master.subjects.index', 'updated');
    }

    public function toggle(Request $request, string $id): Response
    {
        $record = $this->load($request, (int) $id);
        $active = (int) $record['is_active'] === 1;

        $this->subjects->setActive((int) $record['id'], !$active);
        $this->auditChange(
            $request,
            $active ? 'master.subject.archived' : 'master.subject.restored',
            'subject',
            (int) $record['id'],
            ($active ? 'Archived' : 'Restored') . ' subject ' . $record['code']
        );

        return $this->saved('master.subjects.index', $active ? 'archived' : 'restored');
    }

    /**
     * @param array<string, mixed>|null $record
     */
    private function form(Request $request, ?array $record): Response
    {
        $scope = $this->scope($request);

        return $this->view('master/subjects/form', [
            'title' => $record === null ? 'New subject' : 'Edit ' . $record['code'],
            'subject' => $record,
            'departments' => $this->departmentOptions($scope),
            'subject_types' => SubjectRepository::TYPES,
            'room_types' => SubjectRepository::ROOM_TYPES,
            'can_edit' => $this->authorization->can($this->actor($request), $record === null ? 'subjects.create' : 'subjects.update'),
        ]);
    }

    /**
     * @return array<string, mixed>
     */
    private function load(Request $request, int $id): array
    {
        return $this->requireRecord(
            $this->subjects->findInScope($this->scope($request), $id),
            'That subject does not exist.'
        );
    }

    /**
     * @return array<string, mixed>
     */
    private function validateSubject(Request $request): array
    {
        return $this->validate(
            [
                'code' => 'required|alpha_dash|max:30',
                'title' => 'required|string|max:180',
                'department_id' => 'required|integer|min:1',
                'units' => 'required|numeric|min:0|max:12',
                'lecture_hours' => 'required|numeric|min:0|max:12',
                'lab_hours' => 'required|numeric|min:0|max:12',
                'subject_type' => 'required|in:' . implode(',', SubjectRepository::TYPES),
                'preferred_room_type' => 'in:' . implode(',', SubjectRepository::ROOM_TYPES),
                'description' => 'string|max:2000',
            ],
            [
                'code' => 'Subject code',
                'title' => 'Subject title',
                'department_id' => 'Department',
                'units' => 'Units',
                'lecture_hours' => 'Lecture hours',
                'lab_hours' => 'Laboratory hours',
                'subject_type' => 'Subject type',
                'preferred_room_type' => 'Preferred room type',
                'description' => 'Description',
            ]
        );
    }
}
